CONTA_CABECALHO = r"""
WITH GLOSA AS (
    SELECT
        G.CD_REG_AMB,
        COUNT(DISTINCT G.CD_GLOSAS) AS QT_EVENTOS_GLOSA,
        SUM(NVL(G.VL_GLOSA,0)) AS VL_GLOSA_BRUTA,
        SUM(CASE WHEN G.CD_MOTIVO_GLOSA = 324 THEN 0 ELSE NVL(G.VL_GLOSA,0) END) AS VL_GLOSA_LIQUIDA,
        SUM(NVL(G.VL_REAPRESENTADO,0)) AS VL_REAPRESENTADO,
        SUM(NVL(G.VL_RECURSO_REPASSADO,0)) AS VL_RECURSO_REPASSADO
    FROM DBAMV.GLOSAS G
    WHERE G.CD_REG_AMB = :cd_reg_amb
    GROUP BY G.CD_REG_AMB
),
CONTA_ATEND AS (
    SELECT
        IRA.CD_REG_AMB,
        MIN(IRA.CD_ATENDIMENTO) AS CD_ATENDIMENTO,
        COUNT(DISTINCT IRA.CD_ATENDIMENTO) AS QT_ATENDIMENTOS_CONTA
    FROM DBAMV.ITREG_AMB IRA
    WHERE IRA.CD_REG_AMB = :cd_reg_amb
      AND IRA.CD_CONVENIO = 11
    GROUP BY IRA.CD_REG_AMB
),
RECEB AS (
    SELECT
        INF.CD_REG_AMB,
        COUNT(DISTINCT R.CD_RECCON_REC) AS QT_EVENTOS_RECEBIMENTO,
        MIN(R.DT_RECEBIMENTO) AS PRIMEIRO_RECEBIMENTO,
        MAX(R.DT_RECEBIMENTO) AS ULTIMO_RECEBIMENTO,
        SUM(NVL(V.VL_RECEBIDO,0)) AS VL_RECEBIDO_FINANCEIRO,
        SUM(NVL(V.VL_RECEBIDO,0)-NVL(V.VL_ACRESCIMO,0)) AS VL_RECEBIDO_BASE,
        SUM(NVL(V.VL_ACRESCIMO,0)) AS VL_ACRESCIMO_RECEBIMENTO,
        SUM(NVL(V.VL_GLOSA,0)) AS VL_GLOSA_RECEBIMENTO
    FROM DBAMV.ITFAT_NOTA_FISCAL INF
    JOIN DBAMV.V_AJUSTES_RECEBIMENTO_DET V ON V.CD_ITFAT_NF = INF.CD_ITFAT_NF
    JOIN DBAMV.RECCON_REC R ON R.CD_RECCON_REC = V.CD_RECCON_REC
    WHERE INF.CD_REG_AMB = :cd_reg_amb
      AND R.DT_ESTORNO IS NULL
    GROUP BY INF.CD_REG_AMB
)
SELECT
    P.CD_PACIENTE,
    P.NM_PACIENTE,
    A.CD_ATENDIMENTO,
    A.DT_ATENDIMENTO,
    RA.CD_REG_AMB,
    RA.DT_LANCAMENTO,
    RA.CD_REMESSA,
    RA.DT_REMESSA,
    RF.NR_REMESSA_CONVENIO,
    RF.DT_ABERTURA AS DT_ABERTURA_REMESSA,
    RF.DT_FECHAMENTO AS DT_FECHAMENTO_REMESSA,
    RF.DT_ENTREGA_DA_FATURA,
    RF.SN_FECHADA,
    RF.SN_PAGA,
    RA.CD_CONVENIO,
    NVL(RA.VL_TOTAL_CONTA,0) AS VL_FATURADO,
    NVL(G.VL_GLOSA_BRUTA,0) AS VL_GLOSA_BRUTA,
    NVL(G.VL_GLOSA_LIQUIDA,0) AS VL_GLOSA_LIQUIDA,
    NVL(G.VL_REAPRESENTADO,0) AS VL_REAPRESENTADO,
    NVL(G.VL_RECURSO_REPASSADO,0) AS VL_RECURSO_REPASSADO,
    NVL(R.VL_RECEBIDO_FINANCEIRO,0) AS VL_RECEBIDO_FINANCEIRO,
    NVL(R.VL_RECEBIDO_BASE,0) AS VL_RECEBIDO_BASE,
    NVL(R.VL_ACRESCIMO_RECEBIMENTO,0) AS VL_ACRESCIMO_RECEBIMENTO,
    NVL(R.VL_GLOSA_RECEBIMENTO,0) AS VL_GLOSA_RECEBIMENTO,
    NVL(R.QT_EVENTOS_RECEBIMENTO,0) AS QT_EVENTOS_RECEBIMENTO,
    R.PRIMEIRO_RECEBIMENTO,
    R.ULTIMO_RECEBIMENTO,
    GREATEST(NVL(RA.VL_TOTAL_CONTA,0)-NVL(R.VL_RECEBIDO_BASE,0),0) AS VL_SALDO_ESTIMADO,
    CASE
      WHEN RA.CD_REMESSA IS NULL THEN 'SEM_REMESSA'
      WHEN NVL(R.VL_RECEBIDO_BASE,0) <= 0 AND RF.SN_PAGA='S' THEN 'REMESSA_PAGA_SEM_RECEBIMENTO'
      WHEN NVL(R.VL_RECEBIDO_BASE,0) <= 0 THEN 'AGUARDANDO_RECEBIMENTO'
      WHEN NVL(R.VL_RECEBIDO_BASE,0) + 0.01 < NVL(RA.VL_TOTAL_CONTA,0) THEN 'PARCIALMENTE_RECEBIDA'
      WHEN NVL(G.VL_GLOSA_LIQUIDA,0) > 0 THEN 'RECEBIDA_COM_GLOSA'
      ELSE 'RECEBIDA'
    END AS STATUS_FINANCEIRO
FROM DBAMV.REG_AMB RA
JOIN CONTA_ATEND CA ON CA.CD_REG_AMB = RA.CD_REG_AMB
JOIN DBAMV.ATENDIME A ON A.CD_ATENDIMENTO = CA.CD_ATENDIMENTO
LEFT JOIN DBAMV.PACIENTE P ON P.CD_PACIENTE = A.CD_PACIENTE
LEFT JOIN DBAMV.REMESSA_FATURA RF ON RF.CD_REMESSA = RA.CD_REMESSA
LEFT JOIN GLOSA G ON G.CD_REG_AMB = RA.CD_REG_AMB
LEFT JOIN RECEB R ON R.CD_REG_AMB = RA.CD_REG_AMB
WHERE RA.CD_REG_AMB = :cd_reg_amb
  AND RA.CD_CONVENIO = 11
  AND EXISTS (
      SELECT 1 FROM DBAMV.ITREG_AMB IRA
      JOIN DBAMV.AGENDAMENTO_ONCOLOGICO AO ON AO.CD_ATENDIMENTO = IRA.CD_ATENDIMENTO
      WHERE IRA.CD_REG_AMB = RA.CD_REG_AMB
        AND IRA.CD_CONVENIO = 11
        AND AO.CD_CONVENIO = 11
  )
"""

