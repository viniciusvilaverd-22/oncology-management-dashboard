from .common import ONCO_BASE

# Detalhes do coorte assistencial selecionado por DT_PRODUCAO.
# Recebimentos sao acumulados por conta (todas as datas), usando a cadeia financeira validada.
_DETALHES_BASE = ONCO_BASE + r"""
, GLOSA AS (
    SELECT
        G.CD_REG_AMB,
        COUNT(DISTINCT G.CD_GLOSAS) AS QT_EVENTOS_GLOSA,
        SUM(NVL(G.VL_GLOSA,0)) AS VL_GLOSA_BRUTA,
        SUM(CASE WHEN G.CD_MOTIVO_GLOSA = 324 THEN NVL(G.VL_GLOSA,0) ELSE 0 END) AS VL_GLOSA_REVERTIDA,
        SUM(CASE WHEN G.CD_MOTIVO_GLOSA = 324 THEN 0 ELSE NVL(G.VL_GLOSA,0) END) AS VL_GLOSA_LIQUIDA,
        SUM(NVL(G.VL_REAPRESENTADO,0)) AS VL_REAPRESENTADO,
        SUM(NVL(G.VL_RECEBIDO,0)) AS VL_RECEBIDO_GLOSA,
        SUM(NVL(G.VL_RECURSO_REPASSADO,0)) AS VL_RECURSO_REPASSADO
    FROM DBAMV.GLOSAS G
    JOIN (SELECT DISTINCT CD_REG_AMB FROM CONTAS_ONCO) C ON C.CD_REG_AMB = G.CD_REG_AMB
    GROUP BY G.CD_REG_AMB
),
RECEB_CONTA AS (
    SELECT
        INF.CD_REG_AMB,
        COUNT(DISTINCT R.CD_RECCON_REC) AS QT_EVENTOS_RECEBIMENTO,
        MIN(R.DT_RECEBIMENTO) AS PRIMEIRO_RECEBIMENTO,
        MAX(R.DT_RECEBIMENTO) AS ULTIMO_RECEBIMENTO,
        SUM(NVL(V.VL_RECEBIDO,0)) AS VL_RECEBIDO_FINANCEIRO,
        SUM(NVL(V.VL_RECEBIDO,0) - NVL(V.VL_ACRESCIMO,0)) AS VL_RECEBIDO_BASE,
        SUM(NVL(V.VL_ACRESCIMO,0)) AS VL_ACRESCIMO_RECEBIMENTO,
        SUM(NVL(V.VL_GLOSA,0)) AS VL_GLOSA_RECEBIMENTO
    FROM DBAMV.ITFAT_NOTA_FISCAL INF
    JOIN (SELECT DISTINCT CD_REG_AMB FROM CONTAS_ONCO) C ON C.CD_REG_AMB = INF.CD_REG_AMB
    JOIN DBAMV.V_AJUSTES_RECEBIMENTO_DET V ON V.CD_ITFAT_NF = INF.CD_ITFAT_NF
    JOIN DBAMV.RECCON_REC R ON R.CD_RECCON_REC = V.CD_RECCON_REC
    WHERE R.DT_ESTORNO IS NULL
    GROUP BY INF.CD_REG_AMB
),
NOTA_CONTA AS (
    SELECT
        INF.CD_REG_AMB,
        COUNT(DISTINCT INF.CD_NOTA_FISCAL) AS QT_NOTAS_FISCAIS,
        COUNT(DISTINCT INF.CD_ITFAT_NF) AS QT_ITENS_NOTA
    FROM DBAMV.ITFAT_NOTA_FISCAL INF
    JOIN (SELECT DISTINCT CD_REG_AMB FROM CONTAS_ONCO) C ON C.CD_REG_AMB = INF.CD_REG_AMB
    GROUP BY INF.CD_REG_AMB
)
"""

_ATENDIMENTOS_SELECT = r"""
SELECT
    P.CD_PACIENTE,
    P.NM_PACIENTE,
    C.CD_ATENDIMENTO,
    A.DT_ATENDIMENTO,
    C.CD_REG_AMB,
    C.DT_PRIMEIRA_PRODUCAO,
    C.DT_ULTIMA_PRODUCAO,
    RA.DT_LANCAMENTO,
    RA.CD_REMESSA,
    CAST(NULL AS DATE) AS DT_REMESSA,
    RF.NR_REMESSA_CONVENIO,
    RF.DT_FECHAMENTO,
    RF.DT_ENTREGA_DA_FATURA,
    RF.SN_PAGA,
    NVL(RA.VL_TOTAL_CONTA,0) AS VL_FATURADO,
    NVL(G.VL_GLOSA_BRUTA,0) AS VL_GLOSA_BRUTA,
    NVL(G.VL_GLOSA_REVERTIDA,0) AS VL_GLOSA_REVERTIDA,
    NVL(G.VL_GLOSA_LIQUIDA,0) AS VL_GLOSA_LIQUIDA,
    NVL(G.VL_REAPRESENTADO,0) AS VL_REAPRESENTADO,
    NVL(G.VL_RECEBIDO_GLOSA,0) AS VL_RECEBIDO_GLOSA,
    NVL(G.VL_RECURSO_REPASSADO,0) AS VL_RECURSO_REPASSADO,
    NVL(RA.VL_TOTAL_CONTA,0) - NVL(G.VL_GLOSA_LIQUIDA,0) AS VL_POS_GLOSA,
    NVL(G.QT_EVENTOS_GLOSA,0) AS QT_EVENTOS_GLOSA,
    NVL(N.QT_NOTAS_FISCAIS,0) AS QT_NOTAS_FISCAIS,
    NVL(N.QT_ITENS_NOTA,0) AS QT_ITENS_NOTA,
    NVL(RC.QT_EVENTOS_RECEBIMENTO,0) AS QT_EVENTOS_RECEBIMENTO,
    RC.PRIMEIRO_RECEBIMENTO,
    RC.ULTIMO_RECEBIMENTO,
    NVL(RC.VL_RECEBIDO_FINANCEIRO,0) AS VL_RECEBIDO_FINANCEIRO,
    NVL(RC.VL_RECEBIDO_BASE,0) AS VL_RECEBIDO_BASE,
    NVL(RC.VL_ACRESCIMO_RECEBIMENTO,0) AS VL_ACRESCIMO_RECEBIMENTO,
    GREATEST(NVL(RA.VL_TOTAL_CONTA,0) - NVL(RC.VL_RECEBIDO_BASE,0),0) AS VL_SALDO_ESTIMADO,
    CASE
      WHEN RA.CD_REMESSA IS NULL THEN 'SEM_REMESSA'
      WHEN NVL(RC.VL_RECEBIDO_BASE,0) <= 0 AND RF.SN_PAGA = 'S' THEN 'REMESSA_PAGA_SEM_RECEBIMENTO'
      WHEN NVL(RC.VL_RECEBIDO_BASE,0) <= 0 THEN 'AGUARDANDO_RECEBIMENTO'
      WHEN NVL(RC.VL_RECEBIDO_BASE,0) + 0.01 < NVL(RA.VL_TOTAL_CONTA,0) THEN 'PARCIALMENTE_RECEBIDA'
      ELSE 'RECEBIDA'
    END AS STATUS_FINANCEIRO,
    CASE
      WHEN RC.PRIMEIRO_RECEBIMENTO IS NOT NULL AND A.DT_ATENDIMENTO IS NOT NULL
      THEN TRUNC(RC.PRIMEIRO_RECEBIMENTO) - TRUNC(A.DT_ATENDIMENTO)
    END AS DIAS_ATE_PRIMEIRO_RECEBIMENTO
"""

_ATENDIMENTOS_FROM = r"""
FROM CONTAS_ONCO C
JOIN DBAMV.REG_AMB RA ON RA.CD_REG_AMB = C.CD_REG_AMB
JOIN DBAMV.ATENDIME A ON A.CD_ATENDIMENTO = C.CD_ATENDIMENTO
LEFT JOIN DBAMV.PACIENTE P ON P.CD_PACIENTE = A.CD_PACIENTE
LEFT JOIN DBAMV.REMESSA_FATURA RF ON RF.CD_REMESSA = RA.CD_REMESSA
LEFT JOIN GLOSA G ON G.CD_REG_AMB = C.CD_REG_AMB
LEFT JOIN RECEB_CONTA RC ON RC.CD_REG_AMB = C.CD_REG_AMB
LEFT JOIN NOTA_CONTA N ON N.CD_REG_AMB = C.CD_REG_AMB
"""

ATENDIMENTOS_DETALHE = _DETALHES_BASE + _ATENDIMENTOS_SELECT + r""",
    CAST(NULL AS NUMBER) AS VL_CUSTO_MEDICAMENTO
""" + _ATENDIMENTOS_FROM + r"""
ORDER BY A.DT_ATENDIMENTO DESC, C.CD_ATENDIMENTO DESC, C.CD_REG_AMB DESC
"""

