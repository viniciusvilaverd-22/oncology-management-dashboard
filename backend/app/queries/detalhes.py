REMESSAS_RESUMO = _DETALHES_BASE + r"""
SELECT
    RA.CD_REMESSA,
    RF.NR_REMESSA_CONVENIO,
    RF.DT_ABERTURA,
    RF.DT_FECHAMENTO,
    RF.DT_ENTREGA_DA_FATURA,
    RF.SN_FECHADA,
    RF.SN_PAGA,
    COUNT(DISTINCT C.CD_REG_AMB) AS QT_CONTAS,
    COUNT(DISTINCT C.CD_ATENDIMENTO) AS QT_ATENDIMENTOS,
    COUNT(DISTINCT P.CD_PACIENTE) AS QT_PACIENTES,
    SUM(NVL(RA.VL_TOTAL_CONTA,0)) AS VL_FATURADO,
    SUM(NVL(G.VL_GLOSA_BRUTA,0)) AS VL_GLOSA_BRUTA,
    SUM(NVL(G.VL_GLOSA_LIQUIDA,0)) AS VL_GLOSA_LIQUIDA,
    SUM(NVL(RA.VL_TOTAL_CONTA,0) - NVL(G.VL_GLOSA_LIQUIDA,0)) AS VL_POS_GLOSA,
    SUM(NVL(RC.VL_RECEBIDO_FINANCEIRO,0)) AS VL_RECEBIDO_FINANCEIRO,
    SUM(NVL(RC.VL_RECEBIDO_BASE,0)) AS VL_RECEBIDO_BASE,
    SUM(NVL(RC.VL_ACRESCIMO_RECEBIMENTO,0)) AS VL_ACRESCIMO_RECEBIMENTO,
    SUM(GREATEST(NVL(RA.VL_TOTAL_CONTA,0) - NVL(RC.VL_RECEBIDO_BASE,0),0)) AS VL_SALDO_ESTIMADO,
    COUNT(DISTINCT CASE WHEN NVL(RC.VL_RECEBIDO_BASE,0) > 0 THEN C.CD_REG_AMB END) AS QT_CONTAS_COM_RECEBIMENTO,
    MIN(RC.PRIMEIRO_RECEBIMENTO) AS PRIMEIRO_RECEBIMENTO,
    MAX(RC.ULTIMO_RECEBIMENTO) AS ULTIMO_RECEBIMENTO,
    CASE
      WHEN SUM(NVL(RC.VL_RECEBIDO_BASE,0)) <= 0 AND RF.SN_PAGA='S' THEN 'PAGA_SEM_RECEBIMENTO'
      WHEN SUM(NVL(RC.VL_RECEBIDO_BASE,0)) <= 0 THEN 'AGUARDANDO_RECEBIMENTO'
      WHEN SUM(NVL(RC.VL_RECEBIDO_BASE,0)) + 0.01 < SUM(NVL(RA.VL_TOTAL_CONTA,0)) THEN 'PARCIALMENTE_RECEBIDA'
      ELSE 'RECEBIDA'
    END AS STATUS_RECEBIMENTO
FROM CONTAS_ONCO C
JOIN DBAMV.REG_AMB RA ON RA.CD_REG_AMB = C.CD_REG_AMB
JOIN DBAMV.ATENDIME A ON A.CD_ATENDIMENTO = C.CD_ATENDIMENTO
LEFT JOIN DBAMV.PACIENTE P ON P.CD_PACIENTE = A.CD_PACIENTE
LEFT JOIN DBAMV.REMESSA_FATURA RF ON RF.CD_REMESSA = RA.CD_REMESSA
LEFT JOIN GLOSA G ON G.CD_REG_AMB = C.CD_REG_AMB
LEFT JOIN RECEB_CONTA RC ON RC.CD_REG_AMB = C.CD_REG_AMB
WHERE RA.CD_REMESSA IS NOT NULL
GROUP BY RA.CD_REMESSA, RF.NR_REMESSA_CONVENIO, RF.DT_ABERTURA, RF.DT_FECHAMENTO,
         RF.DT_ENTREGA_DA_FATURA, RF.SN_FECHADA, RF.SN_PAGA
ORDER BY RF.DT_FECHAMENTO DESC NULLS LAST, RA.CD_REMESSA DESC
"""

